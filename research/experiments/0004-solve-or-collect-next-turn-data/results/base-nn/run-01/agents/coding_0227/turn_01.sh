import sys

def levenshtein(s1, s2):
    m, n = len(s1), len(s2)
    dp = list(range(n + 1))
    for i in range(1, m + 1):
        prev = dp[0]
        dp[0] = i
        for j in range(1, n + 1):
            temp = dp[j]
            if s1[i-1] == s2[j-1]:
                dp[j] = prev
            else:
                dp[j] = 1 + min(prev, dp[j], dp[j-1])
            prev = temp
    return dp[n]

def main():
    lines = sys.stdin.read().splitlines()
    if len(lines) >= 2:
        s1 = lines[0]
        s2 = lines[1]
    else:
        return
    print(levenshtein(s1, s2))

if __name__ == "__main__":
